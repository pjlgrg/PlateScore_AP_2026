\set ON_ERROR_STOP on

BEGIN;
CREATE SCHEMA platescore;
SET search_path TO platescore;

CREATE TABLE users (
    user_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name varchar(100) NOT NULL,
    email varchar(254) NOT NULL UNIQUE,
    password_hash text NOT NULL,
    role varchar(10) NOT NULL DEFAULT 'student',
    created_at timestamptz NOT NULL DEFAULT current_timestamp,
    CHECK (length(trim(full_name)) > 0),
    CHECK (email = lower(email) AND email ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$'),
    CHECK (length(password_hash) > 0),
    CHECK (role IN ('student', 'manager'))
);

CREATE TABLE meals (
    meal_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meal_type varchar(10) NOT NULL,
    meal_date date NOT NULL,
    published_by integer NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    is_published boolean NOT NULL DEFAULT false,
    UNIQUE (meal_type, meal_date),
    CHECK (meal_type IN ('breakfast', 'lunch', 'snacks', 'dinner'))
);

CREATE TABLE dishes (
    dish_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dish_name varchar(100) NOT NULL UNIQUE,
    description varchar(300),
    CHECK (length(trim(dish_name)) > 0)
);

CREATE TABLE menu_items (
    meal_id integer NOT NULL REFERENCES meals(meal_id) ON DELETE RESTRICT,
    dish_id integer NOT NULL REFERENCES dishes(dish_id) ON DELETE RESTRICT,
    PRIMARY KEY (meal_id, dish_id)
);

CREATE TABLE ratings (
    rating_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id integer NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    meal_id integer NOT NULL REFERENCES meals(meal_id) ON DELETE RESTRICT,
    score smallint NOT NULL,
    comment varchar(300),
    rated_at timestamptz NOT NULL DEFAULT current_timestamp,
    UNIQUE (user_id, meal_id),
    CHECK (score BETWEEN 1 AND 5)
);

COMMIT;
